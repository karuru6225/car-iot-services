"""car_mcpの判定しきい値・上限値。値を変えるときはこのファイルだけを直す。

道具の説明文や返り値の文面（「通常5分ごと」「期間は最大92日」など）もここの値から組み立てるので、
値を変えれば文面も追随する。変えたらテスト（HANDOFF_mnemosyne.md 8章）を回し、デプロイする。"""

# ─── 装置の送信 ───────────────────────────────────────────────────────────────

# 車載装置がDEEP_SLEEPで計測値を送る間隔（esp32_iot_gateway/src/config.hのSLEEP_INTERVAL_SEC）
SEND_INTERVAL_SEC = 300

# 最新の計測がこれより古ければ「今の状態」として扱わない（送信間隔の3回分）
STALE_AFTER_SEC = SEND_INTERVAL_SEC * 3

# ─── バッテリー ───────────────────────────────────────────────────────────────

# メイン電圧がこれ以上なら、オルタネーターが発電している（エンジン稼働中）と推定する。
# 鉛バッテリーの一般的な目安による経験則で、この車両の実測では検証していない
ENGINE_RUNNING_MIN_V = 13.2

# car_status が最新の計測を探しに行く範囲と、直近の推移として返す件数
STATUS_LOOKBACK_HOURS = 24
STATUS_RECENT_ROWS = 6

# ─── トリップ ─────────────────────────────────────────────────────────────────

# これより短い走行の燃費は、燃料流量の積分誤差が支配的なので参考外とする
ECONOMY_MIN_DISTANCE_KM = 1.0

# これを超える燃費は物理的にありえないとみなす。OBDの通信断で燃料消費が
# 過小に積算されたケースで、実データで372km/Lが出たことがある
ECONOMY_MAX_PLAUSIBLE_KM_L = 40.0

# ─── 問い合わせの上限（Athenaのスキャン量と応答時間を抑えるため） ──────────────

HISTORY_MAX_DAYS = 92  # car_battery_history の期間
TRIPS_MAX_DAYS = 92  # car_trips の期間
TRIPS_MAX_COUNT = 100  # car_trips が1回で返すトリップ数

# Athenaの完了を待つ上限。API Gatewayの統合タイムアウト（最大30秒）の中で、
# S3の読み取りと応答の組み立てまで終える必要がある
ATHENA_POLL_TIMEOUT_SEC = 20
